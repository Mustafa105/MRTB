import streamlit as st
import pandas as pd
import numpy as np
import xgboost as xgb
import shap
import matplotlib.pyplot as plt

# Layout & Configuration
st.set_page_config(layout="wide", page_title="Lidl Multi-Agent Branch Orchestrator")
st.title("💛 💙 Lidl Store Operations Multi-Agent Platform (MVP)")
st.caption("Proof of Concept simulating automated agent cycles across multiple categories.")

# =====================================================================
# STEP 1: MULTI-CATEGORY SYNTHETIC DATA GENERATION (LIDL STORE CONTEXT)
# =====================================================================
@st.cache_data
def generate_lidl_data():
    np.random.seed(42)
    days = 150

    categories = [
        'Birra (Beverages)',
        'Prodotti da Forno (Bakery)',
        'Ortofrutta (Fresh Produce)',
        'Detersivi (Cleaning Products)'
    ]

    all_data = []
    for cat in categories:
        data = {
            'Category': cat,
            'Price_Euro': np.random.uniform(0.80, 4.50, days),
            'Is_Promo_Volantino': np.random.choice([0, 1], size=days, p=[0.75, 0.25]),
            'In_Store_Display': np.random.choice([0, 1], size=days, p=[0.85, 0.15]),
            'Temperature_C': np.random.uniform(2, 36, days),
            'Store_Traffic_Index': np.random.uniform(50, 150, days), # Foot traffic score
            'Is_Weekend': np.random.choice([0, 1], size=days, p=[5/7, 2/7])
        }
        df_cat = pd.DataFrame(data)

        # Unique sales mechanics per category to teach the model logical differences
        if 'Birra' in cat:
            base = 400 + (df_cat['Store_Traffic_Index'] * 4) + (df_cat['Temperature_C'] * 12) + (df_cat['Is_Promo_Volantino'] * 500)
        elif 'Forno' in cat:
            base = 600 + (df_cat['Store_Traffic_Index'] * 5) - (df_cat['Temperature_C'] * 2) + (df_cat['In_Store_Display'] * 300)
        elif 'Ortofrutta' in cat:
            base = 500 + (df_cat['Store_Traffic_Index'] * 3) + (df_cat['Temperature_C'] * 5) - (df_cat['Price_Euro'] * 80)
        else: # Cleaning
            base = 200 + (df_cat['Store_Traffic_Index'] * 2) + (df_cat['Is_Promo_Volantino'] * 400)

        df_cat['Sales_Volume'] = (base + np.random.normal(0, 30, days)).astype(int).clip(lower=10)
        all_data.append(df_cat)

    return pd.concat(all_data, ignore_index=True)

df_master = generate_lidl_data()

# =====================================================================
# STEP 2: USER SCENARIO SETUP (SIDEBAR CONTROLS)
# =====================================================================
st.sidebar.header("🕹️ Store Scenario Controls")
selected_cat = st.sidebar.selectbox("Select Target Department/Category:", df_master['Category'].unique())

st.sidebar.markdown("---")
st.sidebar.subheader("Live Environmental Inputs")
s_traffic = st.sidebar.slider("Store Foot Traffic Index", 50, 200, 140, help="100 is standard baseline traffic.")
s_weekend = st.sidebar.selectbox("Calendar Day:", ["Weekday", "Weekend (Saturday/Sunday)"])
s_temp = st.sidebar.slider("Forecasted External Temperature (°C)", 0, 42, 32)

st.sidebar.subheader("Current Merchandising Settings")
s_price = st.sidebar.slider("Current Retail Price (€)", 0.50, 5.00, 1.49)
s_promo = st.sidebar.selectbox("Include in Lidl Flyer (Volantino)?", ["No", "Yes"])
s_display = st.sidebar.selectbox("Special Promotional Endcap Display?", ["No", "Yes"])

st.sidebar.markdown("---")
st.sidebar.subheader("📦 Real-Time Inventory Status")
current_backroom_stock = st.sidebar.number_input("Current Backroom Stock Units Available", min_value=0, value=350, step=50)

# Filter data for chosen category and train the predictive engine
df_filtered = df_master[df_master['Category'] == selected_cat].copy()
X = df_filtered.drop(columns=['Category', 'Sales_Volume'])
y = df_filtered['Sales_Volume']

model = xgb.XGBRegressor(n_estimators=60, max_depth=4, random_state=42)
model.fit(X, y)

explainer = shap.TreeExplainer(model)

# Map UI to inputs
input_row = pd.DataFrame([{
    'Price_Euro': s_price,
    'Is_Promo_Volantino': 1 if s_promo == "Yes" else 0,
    'In_Store_Display': 1 if s_display == "Yes" else 0,
    'Temperature_C': s_temp,
    'Store_Traffic_Index': s_traffic,
    'Is_Weekend': 1 if s_weekend == "Weekend (Saturday/Sunday)" else 0
}])

# Execute prediction and SHAP calculation
predicted_sales = int(model.predict(input_row)[0])
shap_values = explainer(input_row)

impact_df = pd.DataFrame({
    'Feature': X.columns,
    'Impact': shap_values.values[0],
    'Abs_Impact': np.abs(shap_values.values[0])
}).sort_values(by='Abs_Impact', ascending=False)

clean_labels = {
    'Price_Euro': 'Pricing Strategy',
    'Is_Promo_Volantino': 'Flyer Advertisement',
    'In_Store_Display': 'Endcap Placement',
    'Temperature_C': 'Weather Variables',
    'Store_Traffic_Index': 'Branch Foot Traffic',
    'Is_Weekend': 'Weekend Shopper Surge'
}

# =====================================================================
# STEP 3: INTERACTIVE MULTI-AGENT ORCHESTRATION PIPELINE (MAIN WORKSPACE)
# =====================================================================
st.subheader("🤖 Autonomous Agent Orchestration Pipeline")
st.write("Click below to trigger the synchronous multi-agent evaluation lifecycle based on your scenario inputs.")

# Session state to simulate sequential execution steps
if 'simulation_triggered' not in st.session_state:
    st.session_state.simulation_triggered = False

if st.button("🚀 Trigger Live Agent Cycle", type="primary"):
    st.session_state.simulation_triggered = True

if st.session_state.simulation_triggered:

    # -----------------------------------------------------------------
    # AGENT 1: DEMAND ENGINE & XAI CO-PILOT
    # -----------------------------------------------------------------
    st.markdown("### 🛰️ Agent 1: Demand & Explainable AI (XAI) Agent")
    col1, col2 = st.columns()

    with col1:
        st.metric(
            label=f"Forecasted Demand Plan for: {selected_cat}",
            value=f"{predicted_sales} Units Today",
            delta=f"{int(predicted_sales - y.mean())} vs Historic Category Average"
        )

        # FIXED: Corrected positional extraction parameters via integer indices
        top_driver_raw = impact_df.iloc[0]['Feature']
        second_driver_raw = impact_df.iloc[1]['Feature']

        top_direction = "positively" if impact_df.iloc[0]['Impact'] > 0 else "negatively"
        second_direction = "positively" if impact_df.iloc[1]['Impact'] > 0 else "negatively"

        nlg_explanation = f"""
        **Agent Analysis:** The system projects a target demand plan of **{predicted_sales} units**.
        By utilizing **SHAP attribution parameters**, the agent has mapped external variables to internal store traffic dynamics:
        * **Primary Catalyst:** `{clean_labels[top_driver_raw]}` is heavily shifting the demand baseline **{top_direction}**.
        * **Secondary Infrastructure Linkage:** The demand change is intrinsically tied to `{clean_labels[second_driver_raw]}`, driving the loop trajectory **{second_direction}**.
        """
        st.info(nlg_explanation)

    with col2:
        # Mini SHAP render
        fig, ax = plt.subplots(figsize=(5, 3.2))
        display_df = impact_df.copy()
        display_df['Clean'] = display_df['Feature'].map(clean_labels)
        colors = ['#ff0051' if x < 0 else '#008bfb' for x in display_df['Impact']]
        ax.barh(display_df['Clean'], display_df['Impact'], color=colors)
        ax.axvline(x=0, color='black', linestyle='--', linewidth=0.8)
        ax.tick_params(axis='both', which='major', labelsize=8)
        plt.tight_layout()
        st.pyplot(fig)

    st.markdown("---")

    # -----------------------------------------------------------------
    # AGENT 2: SUPPLY CHAIN & STOCK ALLOCATION AGENT
    # -----------------------------------------------------------------
    st.markdown("### 📦 Agent 2: Inventory & Logistical Safety Orchestrator")

    stock_delta = current_backroom_stock - predicted_sales

    col_inv1, col_inv2 = st.columns(2)
    with col_inv1:
        st.metric(label="Expected Stock Level at End-of-Day", value=f"{stock_delta} Units", delta="Risk Status" if stock_delta < 50 else "Safe Status", delta_color="inverse" if stock_delta < 50 else "normal")

    with col_inv2:
        if stock_delta < 50:
            st.error(f"""
            🚨 **CRITICAL INVENTORY ALERT:** Forecasted sales ({predicted_sales} units) will exhaust your available stock pool ({current_backroom_stock} units).

            **Action Executed:** The Logistics Agent has automatically bypassed store approval to dispatch an expedited restock order of **{int(predicted_sales * 1.5)} units** to the Regional Distribution Center (RDC). Delivery window targeted before 06:00 tomorrow morning.
            """)
        else:
            st.success(f"⚖️ **Inventory Equilibrium:** Current store allocation ({current_backroom_stock} units) is sufficient to safely absorb the predicted customer demand spike.")

    st.markdown("---")

    # -----------------------------------------------------------------
    # AGENT 3: COMMERCIAL & MERCHANDISING OPTIMIZATION AGENT
    # -----------------------------------------------------------------
    st.markdown("### 🎯 Agent 3: Commercial Pricing & Cross-Merchandising Layout Agent")

    # Contextual Cross-Merchandising Logic Matrix
    if 'Birra' in selected_cat:
        rec_bundle = """🍿 **Cross-Merchandising Cross-Over:** High temperature and weekend trends indicate social gathering purchasing habits.
        Dynamically construct a thematic island display in Aisle 4 combining **Lidl 'Alesto' Pretzels, Popcorn, and Tortilla Chips** immediately adjacent to the cold beer cases."""

        rec_pricing = """💰 **Dynamic Revenue Optimization:** Demand parameters are rigid.
        Increase current item baseline price by **+5%** or introduce a *'Buy 4 pay for 3'* bundle promotion via the Lidl Plus mobile app to maximize total category margin without bottlenecking check-out velocity."""

    elif 'Forno' in selected_cat:
        rec_bundle = """🧀 **Cross-Merchandising Cross-Over:** High traffic volume in the bakery cluster creates cross-sell affinity loops.
        Place high-margin **Lidl 'Italiamo' Spreads and Fresh Cheeses** directly on display trays above the fresh bread bins."""

        rec_pricing = """💰 **Dynamic Revenue Optimization:** Fresh items require rapid turnover.
        Implement a **30% price reduction** after 18:00 today using electronic shelf labels (ESLs) to ensure total inventory clearance before store closing."""

    elif 'Ortofrutta' in selected_cat:
        rec_bundle = """🥗 **Cross-Merchandising Cross-Over:** Fresh produce demand spikes during peak traffic.
        Relocate **Lidl private label Salad Dressings and Olive Oils** directly to the perimeter bins next to pre-washed leafy greens."""

        rec_pricing = """💰 **Dynamic Revenue Optimization:** Price sensitivity is high here.
        Maintain current pricing but activate a digital discount coupon exclusively on the Lidl Plus App to lock in volume against local supermarket rivals."""

    else: # Cleaning
        rec_bundle = """🧻 **Cross-Merchandising Cross-Over:** Household cleaning purchases correlate with standard bulk shopping.
        Create a multi-buy endcap combining **Fabric Softeners alongside Multi-pack Paper Towels** near the entry zone."""

        rec_pricing = """💰 **Dynamic Revenue Optimization:** Stable velocity dictates flat pricing.
        Maintain current margins but allocate additional shelf face limits (+2 slots) to optimize layout visibility."""

    # Display Agent 3 Outputs
    st.info(rec_bundle)
    st.success(rec_pricing)